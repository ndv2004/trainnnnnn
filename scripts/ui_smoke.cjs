// Optional QA only: npm package playwright and a Chromium installation are required.
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const base = process.env.UI_BASE || 'http://127.0.0.1:8000';
const assets = path.join(root, 'test_data');
const report = { scope: 'real browser + real local models + replay fixtures; no physical webcam', steps: [], errors: [] };
const assert = (condition, message) => { if (!condition) throw new Error(message); };
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox']});
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
  page.on('pageerror', e => report.errors.push(e.message));
  try {
    await page.goto(base);
    await page.waitForFunction(() => document.querySelector('#readiness').textContent.includes('sẵn sàng'));
    assert(await page.title() === 'Exam Watch · Giám sát thử nghiệm', 'Wrong title');
    assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Desktop overflow');
    await page.setViewportSize({width: 390, height: 844});
    assert(!await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), 'Mobile overflow');
    await page.setViewportSize({width: 1440, height: 1100});
    report.steps.push('Desktop and mobile layout, API readiness');
    await page.locator('[data-tab="admin"]').click();
    await page.locator('#profile-file').setInputFiles(path.join(assets,'reference.jpg'));
    await page.locator('#profile-source').fill('public-fixture-browser-smoke-only');
    await page.locator('#profile-attest').check();
    await page.locator('#enroll').click();
    await page.waitForFunction(() => document.querySelector('#admin-feedback').textContent.includes('Đã đăng ký'));
    report.steps.push('Admin registers a separate reference using real SFace');
    await page.locator('[data-tab="candidate"]').click();
    await page.locator('#video-file').setInputFiles(path.join(assets,'reference.webm'));
    await page.waitForFunction(() => document.querySelector('#video').readyState >= 2);
    await page.locator('#consent').check();
    await page.locator('#create-session').click();
    await page.waitForFunction(() => document.querySelector('#session-id').textContent.length > 20);
    const sid = (await page.locator('#session-id').textContent()).trim();
    await page.locator('#precheck').click();
    await page.waitForFunction(() => document.querySelector('#candidate-feedback').textContent.includes('Kiểm tra đạt'));
    await page.locator('#verify').click();
    await page.waitForFunction(() => document.querySelector('#candidate-feedback').textContent.startsWith('MATCH'));
    await page.locator('#calibrate').click();
    await page.waitForFunction(() => document.querySelector('#candidate-feedback').textContent.startsWith('PASSED'), {timeout: 20000});
    await page.locator('#start').click();
    await page.waitForFunction(() => document.querySelector('#candidate-feedback').textContent.includes('Đang gửi ảnh'));
    report.steps.push('Video replay → precheck → real verification → real calibration → monitoring');
    await page.locator('[data-tab="proctor"]').click();
    await page.locator('#load-sessions').click();
    await page.waitForFunction(() => document.querySelector('#proctor-session').options.length > 1);
    await page.locator('#proctor-session').selectOption(sid);
    await page.waitForTimeout(500);
    await page.locator('[data-tab="candidate"]').click();
    await page.locator('#video-file').setInputFiles(path.join(assets,'absence.webm'));
    await page.waitForFunction(() => document.querySelector('#source-status').textContent.includes('video cục bộ'));
    await page.waitForTimeout(300);
    await page.locator('#resume').click();
    await page.waitForFunction(() => document.querySelector('#candidate-feedback').textContent.includes('Đã khôi phục'));
    await page.waitForTimeout(4700);
    await page.locator('#end').click();
    await page.waitForFunction(() => document.querySelector('#session-state').textContent === 'ENDED');
    await page.locator('[data-tab="proctor"]').click();
    await page.waitForFunction(() => document.querySelector('#timeline').textContent.includes('Không phát hiện khuôn mặt'));
    report.steps.push('Source interruption and resume, a single real FACE_NOT_VISIBLE event, session end');
    const event = page.locator('.event').filter({hasText: 'Không phát hiện khuôn mặt'}).first();
    await event.getByRole('button', {name:'Xem minh chứng'}).first().click();
    await page.waitForFunction(() => document.querySelector('#evidence-dialog').open && document.querySelector('#evidence-image').naturalWidth > 0);
    await page.locator('#close-evidence').click();
    await event.locator('.review-row select').selectOption('CONFIRMED_OBSERVATION');
    await event.locator('.review-row input').fill('Đã kiểm tra minh chứng qua UI smoke test');
    await event.getByRole('button',{name:'Lưu xem xét'}).click();
    await page.waitForFunction(() => document.querySelector('#proctor-feedback').textContent.includes('Đã lưu'));
    report.steps.push('Authorized evidence display and human review');
    await page.locator('#proctor-account').selectOption('outsider');
    await page.locator('#load-sessions').click();
    await page.waitForFunction(() => document.querySelector('#proctor-feedback').textContent.startsWith('0 phiên'));
    assert((await page.locator('#timeline').textContent()).includes('Chưa có'), 'Old timeline leaked across role selection');
    report.steps.push('Unassigned demo proctor receives no sessions');
    assert(report.errors.length === 0, 'Browser runtime errors: ' + report.errors.join('; '));
    report.status = 'PASS';
  } catch (e) {
    report.status = 'FAIL';
    report.failure = e.message;
    report.ui_feedback = await page.locator('#candidate-feedback').textContent().catch(()=> '');
    process.exitCode = 1;
  } finally {
    await browser.close();
    fs.writeFileSync(path.join(root,'reports/ui-smoke.json'), JSON.stringify(report,null,2)+'\n');
    console.log(JSON.stringify(report,null,2));
  }
})();
